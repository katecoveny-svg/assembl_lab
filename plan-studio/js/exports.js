// assembl Plan Studio · file exports: IFC4 (BIM), DXF R12 (CAD), and a project JSON. Pure functions, no dependencies.
// The IFC carries each element's evidence (source, confidence) in a property set, so a consultant opening the model in Revit,
// ArchiCAD or Solibri can see what was measured from the drawing and what was inferred.
import { openingSpan, polyArea, isDoor } from "./model.js";
import { MATERIALS } from "./materials.js";

// ------------------------------------------------------------------------------------------------ IFC4 (STEP physical file)
export function toIFC(P, now = new Date()) {
  let n = 0; const L = [];
  const add = (s) => { n++; L.push(`#${n}=${s};`); return `#${n}`; };
  const str = (s) => `'${String(s ?? "").replace(/\\/g, "\\\\").replace(/'/g, "''").replace(/[^\x20-\x7E]/g, (c) => `\\X2\\${c.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0")}\\X0\\`)}'`;
  const num = (x) => { const s = (+x).toFixed(6).replace(/0+$/, ""); return s.endsWith(".") ? s : s.includes(".") ? s : s + "."; };
  const B64 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_$";
  const guid = (seed) => { let h = 2166136261; const out = []; for (let i = 0; i < 22; i++) { for (const c of seed + i) h = Math.imul(h ^ c.charCodeAt(0), 16777619) >>> 0; out.push(B64[(i === 0 ? h % 4 : h % 64)]); } return out.join(""); };
  const pt = (x, y, z) => add(z === undefined ? `IFCCARTESIANPOINT((${num(x)},${num(y)}))` : `IFCCARTESIANPOINT((${num(x)},${num(y)},${num(z)}))`);
  const dirn = (x, y, z) => add(z === undefined ? `IFCDIRECTION((${num(x)},${num(y)}))` : `IFCDIRECTION((${num(x)},${num(y)},${num(z)}))`);
  const ax3 = (o, z, x) => add(`IFCAXIS2PLACEMENT3D(${o},${z || "$"},${x || "$"})`);
  const m = (v) => v / 1000;   // model mm → IFC metres

  const ts = Math.floor(now.getTime() / 1000);
  const owner = (() => {
    const person = add(`IFCPERSON($,${str(P.meta.designer)},$,$,$,$,$,$)`), org = add(`IFCORGANIZATION($,${str("assembl")},$,$,$)`);
    const po = add(`IFCPERSONANDORGANIZATION(${person},${org},$)`), app = add(`IFCAPPLICATION(${org},${str("0.1")},${str("assembl Plan Studio")},${str("assembl-plan-studio")})`);
    return add(`IFCOWNERHISTORY(${po},${app},$,.ADDED.,$,$,$,${ts})`);
  })();
  const origin = pt(0, 0, 0), Z = dirn(0, 0, 1), Xd = dirn(1, 0, 0), world = ax3(origin, Z, Xd);
  const ctx = add(`IFCGEOMETRICREPRESENTATIONCONTEXT($,'Model',3,1.E-05,${world},$)`);
  const body = add(`IFCGEOMETRICREPRESENTATIONSUBCONTEXT('Body','Model',*,*,*,*,${ctx},$,.MODEL_VIEW.,$)`);
  const units = add(`IFCUNITASSIGNMENT((${add("IFCSIUNIT(*,.LENGTHUNIT.,$,.METRE.)")},${add("IFCSIUNIT(*,.AREAUNIT.,$,.SQUARE_METRE.)")},${add("IFCSIUNIT(*,.VOLUMEUNIT.,$,.CUBIC_METRE.)")},${add("IFCSIUNIT(*,.PLANEANGLEUNIT.,$,.RADIAN.)")}))`);
  const project = add(`IFCPROJECT(${str(guid("project" + P.meta.number))},${owner},${str(P.meta.name)},${str("Generated by assembl Plan Studio. Elements carry Pset_assemblEvidence.")},$,$,$,(${ctx}),${units})`);
  const place = (rel, o) => add(`IFCLOCALPLACEMENT(${rel || "$"},${o || ax3(pt(0, 0, 0))})`);
  const sitePl = place(null), site = add(`IFCSITE(${str(guid("site"))},${owner},${str("Site")},$,$,${sitePl},$,$,.ELEMENT.,$,$,$,${str(P.meta.address)},$)`);
  const bldPl = place(sitePl), bld = add(`IFCBUILDING(${str(guid("building"))},${owner},${str(P.meta.name)},$,$,${bldPl},$,$,.ELEMENT.,$,$,$)`);
  const stPl = place(bldPl), storey = add(`IFCBUILDINGSTOREY(${str(guid("storey"))},${owner},${str("Ground floor")},$,$,${stPl},$,$,.ELEMENT.,0.)`);
  add(`IFCRELAGGREGATES(${str(guid("agg1"))},${owner},$,$,${project},(${site}))`);
  add(`IFCRELAGGREGATES(${str(guid("agg2"))},${owner},$,$,${site},(${bld}))`);
  add(`IFCRELAGGREGATES(${str(guid("agg3"))},${owner},$,$,${bld},(${storey}))`);

  const contained = [], spaces = [], matUse = new Map();
  const rectSolid = (xd, w, h, depth, at = [0, 0, 0]) => {
    const prof = add(`IFCRECTANGLEPROFILEDEF(.AREA.,$,${add(`IFCAXIS2PLACEMENT2D(${pt(xd / 2, 0)},$)`)},${num(xd)},${num(w)})`);
    return add(`IFCEXTRUDEDAREASOLID(${prof},${ax3(pt(...at))},${Z},${num(h)})`);
  };
  const shape = (items) => add(`IFCPRODUCTDEFINITIONSHAPE($,$,(${add(`IFCSHAPEREPRESENTATION(${body},'Body','SweptSolid',(${items.join(",")}))`)}))`);
  const evidence = (el, e) => {
    if (!e) return;
    const props = [add(`IFCPROPERTYSINGLEVALUE('Source',$,IFCLABEL(${str(e.src)}),$)`), add(`IFCPROPERTYSINGLEVALUE('Confidence',$,IFCREAL(${num(e.conf ?? 0)}),$)`), add(`IFCPROPERTYSINGLEVALUE('Note',$,IFCTEXT(${str(e.note || "")}),$)`)];
    const ps = add(`IFCPROPERTYSET(${str(guid("ps" + el))},${owner},'Pset_assemblEvidence',$,(${props.join(",")}))`);
    add(`IFCRELDEFINESBYPROPERTIES(${str(guid("rdp" + el))},${owner},$,$,(${el}),${ps})`);
  };
  const material = (el, id) => { if (!id) return; const k = MATERIALS[id]?.name || id; if (!matUse.has(k)) matUse.set(k, []); matUse.get(k).push(el); };

  for (const w of P.walls) {
    const len = Math.hypot(w.b[0] - w.a[0], w.b[1] - w.a[1]), dx = (w.b[0] - w.a[0]) / len, dy = (w.b[1] - w.a[1]) / len;
    const wp = place(stPl, ax3(pt(m(w.a[0]), m(w.a[1]), 0), Z, dirn(dx, dy, 0)));
    const ext = w.kind === "ext" ? m(w.t) / 2 : 0;
    const solid = rectSolid(m(len) + 2 * ext, m(w.t), m(w.h), [-ext, 0, 0]);
    const wall = add(`IFCWALL(${str(guid("wall" + w.id))},${owner},${str(w.id)},${str(w.kind === "ext" ? "External wall" : "Internal wall")},$,${wp},${shape([solid])},${str(w.id)},.${w.mat === "glass-curtain" ? "NOTDEFINED" : "STANDARD"}.)`);
    contained.push(wall); evidence(wall, w.ev); material(wall, w.mat);
    for (const o of P.openings.filter((x) => x.wall === w.id)) {
      const op_ = place(wp, ax3(pt(m(o.at - o.w / 2), -m(w.t) / 2 - 0.01, m(o.sill))));
      const opening = add(`IFCOPENINGELEMENT(${str(guid("op" + o.id))},${owner},${str("Opening " + o.id)},$,$,${op_},${shape([rectSolid(m(o.w), m(w.t) + 0.02, m(o.h), [0, m(w.t) / 2 + 0.01, 0])])},$,.OPENING.)`);
      add(`IFCRELVOIDSELEMENT(${str(guid("void" + o.id))},${owner},$,$,${wall},${opening})`);
      if (o.kind === "opening") continue;
      const fp = place(op_, ax3(pt(0, m(w.t) / 2 + 0.01 - 0.025, 0)));
      const fill = isDoor(o)
        ? add(`IFCDOOR(${str(guid("door" + o.id))},${owner},${str(o.id)},${str(o.note || "Door")},$,${fp},${shape([rectSolid(m(o.w), 0.05, m(o.h))])},${str(o.id)},${num(m(o.h))},${num(m(o.w))},.${o.kind === "door-double" ? "DOOR" : "DOOR"}.,.${o.kind === "door-double" ? "DOUBLE_DOOR_SINGLE_SWING" : "SINGLE_SWING_LEFT"}.,$)`)
        : add(`IFCWINDOW(${str(guid("win" + o.id))},${owner},${str(o.id)},${str(o.note || "Window")},$,${fp},${shape([rectSolid(m(o.w), 0.05, m(o.h))])},${str(o.id)},${num(m(o.h))},${num(m(o.w))},.WINDOW.,.SINGLE_PANEL.,$)`);
      add(`IFCRELFILLSELEMENT(${str(guid("fill" + o.id))},${owner},$,$,${opening},${fill})`);
      contained.push(fill); evidence(fill, o.ev); material(fill, o.mat);
    }
  }
  // slab under the whole footprint, from the rooms' extent
  const xs = P.rooms.flatMap((r) => r.poly.map((p) => p[0])), ys = P.rooms.flatMap((r) => r.poly.map((p) => p[1]));
  const x0 = Math.min(...xs), y0 = Math.min(...ys), x1 = Math.max(...xs), y1 = Math.max(...ys), st = P.slab?.t || 150;
  const slabSolid = (() => { const prof = add(`IFCRECTANGLEPROFILEDEF(.AREA.,$,${add(`IFCAXIS2PLACEMENT2D(${pt(m((x0 + x1) / 2), m((y0 + y1) / 2))},$)`)},${num(m(x1 - x0))},${num(m(y1 - y0))})`); return add(`IFCEXTRUDEDAREASOLID(${prof},${ax3(pt(0, 0, -m(st)))},${Z},${num(m(st))})`); })();
  const slab = add(`IFCSLAB(${str(guid("slab"))},${owner},'Ground slab',$,$,${place(stPl)},${shape([slabSolid])},$,.FLOOR.)`); contained.push(slab); material(slab, P.slab?.mat);
  // spaces (rooms) as extruded polygons
  for (const r of P.rooms) {
    const pts = r.poly.map((p) => pt(m(p[0]), m(p[1]))), curve = add(`IFCPOLYLINE((${[...pts, pts[0]].join(",")}))`);
    const prof = add(`IFCARBITRARYCLOSEDPROFILEDEF(.AREA.,${str(r.name)},${curve})`), solid = add(`IFCEXTRUDEDAREASOLID(${prof},${ax3(pt(0, 0, 0))},${Z},${num(3)})`);
    const sp = add(`IFCSPACE(${str(guid("space" + r.id))},${owner},${str(r.id)},${str(r.name)},$,${place(stPl)},${shape([solid])},${str(r.name)},.ELEMENT.,.INTERNAL.,$)`);
    spaces.push(sp); evidence(sp, r.ev);
    const q = add(`IFCQUANTITYAREA('NetFloorArea',$,$,${num(polyArea(r.poly) / 1e6)},$)`), eq = add(`IFCELEMENTQUANTITY(${str(guid("q" + r.id))},${owner},'Qto_SpaceBaseQuantities',$,$,(${q}))`);
    add(`IFCRELDEFINESBYPROPERTIES(${str(guid("rq" + r.id))},${owner},$,$,(${sp}),${eq})`);
    const use = add(`IFCPROPERTYSINGLEVALUE('Use',$,IFCLABEL(${str(r.use)}),$)`), occ = add(`IFCPROPERTYSINGLEVALUE('Occupants',$,IFCINTEGER(${Math.round(r.occupants || 0)}),$)`);
    const ps = add(`IFCPROPERTYSET(${str(guid("psu" + r.id))},${owner},'Pset_assemblSpace',$,(${use},${occ}))`); add(`IFCRELDEFINESBYPROPERTIES(${str(guid("rpu" + r.id))},${owner},$,$,(${sp}),${ps})`);
  }
  if (spaces.length) add(`IFCRELAGGREGATES(${str(guid("aggsp"))},${owner},$,$,${storey},(${spaces.join(",")}))`);
  add(`IFCRELCONTAINEDINSPATIALSTRUCTURE(${str(guid("contain"))},${owner},$,$,(${contained.join(",")}),${storey})`);
  let k = 0; for (const [name, els] of matUse) { const mat = add(`IFCMATERIAL(${str(name)},$,$)`); add(`IFCRELASSOCIATESMATERIAL(${str(guid("mat" + k++))},${owner},$,$,(${els.join(",")}),${mat})`); }

  const head = `ISO-10303-21;\nHEADER;\nFILE_DESCRIPTION(('ViewDefinition [ReferenceView]'),'2;1');\nFILE_NAME(${str(P.meta.number + ".ifc")},'${now.toISOString().slice(0, 19)}',(${str(P.meta.designer)}),('assembl'),'assembl Plan Studio','assembl Plan Studio 0.1','');\nFILE_SCHEMA(('IFC4'));\nENDSEC;\nDATA;\n`;
  return head + L.join("\n") + "\nENDSEC;\nEND-ISO-10303-21;\n";
}

// ------------------------------------------------------------------------------------------------ DXF R12: the floor plan
export function toDXF(P) {
  const out = ["0", "SECTION", "2", "HEADER", "9", "$INSUNITS", "70", "4", "9", "$ACADVER", "1", "AC1009", "0", "ENDSEC", "0", "SECTION", "2", "TABLES", "0", "TABLE", "2", "LAYER", "70", "6"];
  const layers = [["A-WALL", 7], ["A-WALL-INT", 8], ["A-GLAZ", 4], ["A-DOOR", 2], ["A-AREA-IDEN", 3], ["A-GRID", 1]];
  for (const [nm, col] of layers) out.push("0", "LAYER", "2", nm, "70", "0", "62", String(col), "6", "CONTINUOUS");
  out.push("0", "ENDTAB", "0", "ENDSEC", "0", "SECTION", "2", "ENTITIES");
  const ln = (lay, a, b) => out.push("0", "LINE", "8", lay, "10", a[0].toFixed(1), "20", a[1].toFixed(1), "30", "0", "11", b[0].toFixed(1), "21", b[1].toFixed(1), "31", "0");
  const tx = (lay, p, h, s) => out.push("0", "TEXT", "8", lay, "10", p[0].toFixed(1), "20", p[1].toFixed(1), "30", "0", "40", String(h), "1", String(s).replace(/[^\x20-\x7E]/g, "?"));
  const arc = (lay, c, r, a0, a1) => out.push("0", "ARC", "8", lay, "10", c[0].toFixed(1), "20", c[1].toFixed(1), "30", "0", "40", r.toFixed(1), "50", a0.toFixed(2), "51", a1.toFixed(2));
  for (const w of P.walls) {
    const len = Math.hypot(w.b[0] - w.a[0], w.b[1] - w.a[1]), d = [(w.b[0] - w.a[0]) / len, (w.b[1] - w.a[1]) / len], n = [-d[1], d[0]], ht = w.t / 2;
    const cuts = P.openings.filter((o) => o.wall === w.id).map((o) => [o.at - o.w / 2, o.at + o.w / 2]).sort((a, b) => a[0] - b[0]);
    let s = 0; const pieces = []; for (const [c0, c1] of cuts) { if (c0 > s) pieces.push([s, c0]); s = Math.max(s, c1); } if (len > s) pieces.push([s, len]);
    const P_ = (t, k) => [w.a[0] + d[0] * t + n[0] * k, w.a[1] + d[1] * t + n[1] * k], lay = w.kind === "ext" ? "A-WALL" : "A-WALL-INT";
    for (const [a, b] of pieces) { ln(lay, P_(a, -ht), P_(b, -ht)); ln(lay, P_(a, ht), P_(b, ht)); ln(lay, P_(a, -ht), P_(a, ht)); ln(lay, P_(b, -ht), P_(b, ht)); }
  }
  for (const o of P.openings) {
    const s = openingSpan(P, o); if (!s) continue; const n = [-s.d[1], s.d[0]];
    if (o.kind === "window" || o.kind === "glazing") ln("A-GLAZ", s.a, s.b);
    else if (isDoor(o) && o.kind !== "opening") {
      const ang = (Math.atan2(s.d[1], s.d[0]) * 180) / Math.PI, r = o.kind === "door-double" ? o.w / 2 : o.w;
      ln("A-DOOR", s.a, [s.a[0] + n[0] * r, s.a[1] + n[1] * r]); arc("A-DOOR", s.a, r, ang, ang + 90);
      if (o.kind === "door-double") { ln("A-DOOR", s.b, [s.b[0] + n[0] * r, s.b[1] + n[1] * r]); arc("A-DOOR", s.b, r, ang + 90, ang + 180); }
    }
  }
  for (const r of P.rooms) { const xs = r.poly.map((p) => p[0]), ys = r.poly.map((p) => p[1]), c = [(Math.min(...xs) + Math.max(...xs)) / 2, (Math.min(...ys) + Math.max(...ys)) / 2]; tx("A-AREA-IDEN", c, 250, r.name.toUpperCase()); tx("A-AREA-IDEN", [c[0], c[1] - 350], 180, `${(polyArea(r.poly) / 1e6).toFixed(1)} m2`); }
  out.push("0", "ENDSEC", "0", "EOF");
  return out.join("\n") + "\n";
}

export const toJSON = (P) => JSON.stringify(P, null, 1);
