"""Bake original elevation drawings into compact sections for Three.js."""
import argparse
import json
import subprocess
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument("checkout", type=Path, help="Local img2threejs checkout")
args = parser.parse_args()
commit = subprocess.check_output(["git", "-C", args.checkout, "rev-parse", "HEAD"], text=True).strip()
if commit != "0c0c49bc168e648dbaf9c8c080474de0b3a941b6":
    sys.exit("Use the img2threejs revision recorded in README.md")
profiles = {}
for name in ("pendant", "turned-leg", "harakeke"):
    result = json.loads(subprocess.check_output([
        sys.executable, args.checkout / "forge/stage2_spec/derive_geometry.py",
        here / "references" / (name + ".png"), "--samples", "32", "--json",
    ]))
    if result["axis"] != "vertical" or len(result["points"]) != 32:
        sys.exit(f"Unexpected outline in {name}")
    radii = [p[0] for p in result["points"]]
    if min(radii) < 0 or min(radii) == max(radii):
        sys.exit(f"Invalid silhouette in {name}")
    profiles[name] = [round(r / max(radii), 3) for r in radii[::-1]]
output = here.parent.parent / "pavilion/design-profiles.js"
output.write_text("// Generated by tools/scene-authoring/profiles.py. Samples run from base to tip.\n"
                  + "export const profiles = " + json.dumps(profiles, indent=None) + ";\n"
                  + """export function widthAt(samples,t){
  const index=Math.min(1,Math.max(0,t))*(samples.length-1),low=Math.floor(index);
  return samples[low]+(samples[Math.min(low+1,samples.length-1)]-samples[low])*(index-low);
}
""")
