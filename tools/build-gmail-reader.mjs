// Builds the Gmail reader for GETS alert emails from the page's own parser, so the two cannot drift.
//   node tools/build-gmail-reader.mjs          writes tools/gmail-gets-reader/Code.gs and architecture/js/gmail-reader-script.js
// The parser is architecture/js/gets-alert.js, copied as it is except for three things Apps Script does not have: ES module syntax,
// the URL class (a small stand-in is added) and Intl time zones (Utilities.formatDate is used). Each of those replacements must find its
// text, or the build stops. tests/architecture/gmail-reader.test.mjs fails when the files on disk are not what this builds.
// Run after changing architecture/js/gets-alert.js or config.js, then node tools/arch-importmap.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY } from '../architecture/js/config.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(path.join(root, f), 'utf8');
export const PLACEHOLDER = 'PASTE-YOUR-READER-TOKEN-HERE';

function must(src, from, to) {
  if (!src.includes(from)) throw new Error(`build-gmail-reader: cannot find ${JSON.stringify(from.slice(0, 60))} in the parser; update this build.`);
  return src.replace(from, to);
}

/** the parser as plain Apps Script */
export function parserSource() {
  let p = read('architecture/js/gets-alert.js');
  p = must(p, "import { isGetsUrl, markupToText } from './hunt-rank.js';\n", '');
  p = p.replace(/^export /gm, '');
  // Intl: Apps Script's V8 has no reliable Intl time zones, but Utilities.formatDate knows Pacific/Auckland
  const start = p.indexOf('const NZ = new Intl.DateTimeFormat'), end = p.indexOf('/** a wall-clock time in New Zealand');
  if (start < 0 || end < 0) throw new Error('build-gmail-reader: cannot find the time zone lines in the parser.');
  p = p.slice(0, start) + `const nzParts = (ms) => { const f = Utilities.formatDate(new Date(ms), 'Pacific/Auckland', 'yyyy-M-d-H-m').split('-').map(Number); return { year: f[0], month: f[1], day: f[2], hour: f[3], minute: f[4] }; };\n` + p.slice(end);
  return p.trim();
}

/** what the parser borrows from the page: the link check, a tag stripper (the script reads plain text, so it is never called) and a URL class */
const BORROWED = `// ---- stand-ins for things the page's code has and Apps Script does not --------------------------------------------------
const markupToText = (s) => String(s).replace(/<[^>]*>/g, ' ');
function URL(text) {
  const m = /^(https?:)\\/\\/(?:([^@\\/?#]*)@)?([^\\/:?#]+)(?::(\\d+))?([^?#]*)(?:\\?([^#]*))?(?:#.*)?$/i.exec(String(text));
  if (!m) throw new Error('not a link');
  this.protocol = m[1].toLowerCase(); this.username = m[2] ? m[2].split(':')[0] : ''; this.password = m[2] && m[2].includes(':') ? m[2].split(':')[1] : '';
  this.hostname = m[3].toLowerCase(); this.port = m[4] || ''; this.pathname = m[5] || '/';
  const q = {}; for (const kv of (m[6] || '').split('&')) { const i = kv.indexOf('='); if (i > 0) { const k = decodeURIComponent(kv.slice(0, i)); if (!(k in q)) q[k] = decodeURIComponent(kv.slice(i + 1)); } }
  this.searchParams = { get: (k) => (Object.prototype.hasOwnProperty.call(q, k) ? q[k] : null) };
}
const isGetsUrl = (url) => { try { const u = new URL(url); return u.protocol === 'https:' && u.hostname === 'www.gets.govt.nz' && !u.port && !u.username && !u.password; } catch (e) { return false; } };`;

const HEAD = (token, url, key) => `// assembl: reads GETS alert emails in this Gmail and files the tenders in the practice's workspace (Found work > Add alert emails).
// GENERATED by tools/build-gmail-reader.mjs from architecture/js/gets-alert.js: do not edit by hand, the page makes a fresh copy for you.
//
// What it does, once an hour: looks for GETS alert emails from the last 3 days that it has not filed yet, reads their plain text, finds the tender
// names, buyers, closing times and gets.govt.nz links, and sends only those to the workspace. It then labels the thread "assembl/filed".
// What it never does: delete, send, forward, reply to or move mail, or send an email's text, sender or recipient anywhere.
//
// PRIVATE: the token below is the key to your practice's alert inbox. Do not share it or post it. Press "Stop the reader" in the workspace to cancel it.
const ASSEMBL_TOKEN = '${token}';

// These two are public (the same ones the workspace page uses); on their own they open nothing.
const SUPABASE_URL = '${url}';
const SUPABASE_KEY = '${key}';

const SEARCH = 'from:noreply@gets.govt.nz subject:"GETS" newer_than:3d -label:assembl/filed';
const LABEL = 'assembl/filed';
const MAX_THREADS = 30, MAX_MESSAGES = 5, MAX_ITEMS_PER_CALL = 300, MAX_BODY = 200000;`;

const BODY = `// ---- the reader ---------------------------------------------------------------------------------------------------------------------------------
/** Run this once: it makes the hourly trigger. Google asks you to approve it the first time. */
function setup() {
  for (const t of ScriptApp.getProjectTriggers()) if (t.getHandlerFunction() === 'run') ScriptApp.deleteTrigger(t);
  ScriptApp.newTrigger('run').timeBased().everyHours(1).create();
  Logger.log('assembl: the hourly reader is set up. Running it once now.');
  run();
}

function run() {
  const label = GmailApp.getUserLabelByName(LABEL) || GmailApp.createLabel(LABEL);
  const threads = GmailApp.search(SEARCH, 0, MAX_THREADS), picked = [], rows = [];
  for (const thread of threads) {
    const found = [];
    for (const msg of thread.getMessages().slice(-MAX_MESSAGES)) {
      const text = 'Subject: ' + msg.getSubject() + '\\n\\n' + String(msg.getPlainBody()).slice(0, MAX_BODY);
      for (const it of parseGetsEmail(text).items) {
        if (it.name) found.push({ rfx_id: it.rfxId, ref: it.ref, organisation: it.organisation, name: it.name, closes_at: it.closes || null, url: it.url, kind: it.kind === 'future' ? 'future' : 'current' });
      }
    }
    if (rows.length + found.length > MAX_ITEMS_PER_CALL) break; // the rest is picked up in the next hour
    rows.push(...found); picked.push(thread);
  }
  if (!picked.length) { Logger.log('assembl: nothing new.'); return; }
  let filed = 0;
  if (rows.length) {
    const res = UrlFetchApp.fetch(SUPABASE_URL + '/rest/v1/rpc/hunt_inbox_ingest', {
      method: 'post', contentType: 'application/json', muteHttpExceptions: true,
      headers: { apikey: SUPABASE_KEY, 'Content-Profile': 'arch' },
      payload: JSON.stringify({ p_token: ASSEMBL_TOKEN, p_items: rows }),
    });
    const code = res.getResponseCode();
    if (code !== 200) { Logger.log('assembl: not filed (HTTP ' + code + '). It will try again next hour. If this keeps happening, make a new reader in the workspace.'); return; }
    filed = Number(res.getContentText()) || 0;
  }
  for (const thread of picked) thread.addLabel(label);
  Logger.log('assembl: read ' + picked.length + ' email thread(s), filed ' + filed + ' notice(s).');
}`;

export function buildScript({ token = PLACEHOLDER, url = SUPABASE_URL, key = SUPABASE_PUBLISHABLE_KEY } = {}) {
  return `${HEAD(token, url, key)}\n\n${BORROWED}\n\n// ---- the parser: a copy of architecture/js/gets-alert.js ------------------------------------------------------------------------------------------\n${parserSource()}\n\n${BODY}\n`;
}
/** the page's module: the script with a placeholder, and a function that puts a token in */
export function buildModule() {
  const tpl = buildScript({ token: '__TOKEN__', url: '__URL__', key: '__KEY__' });
  return `// GENERATED by tools/build-gmail-reader.mjs from architecture/js/gets-alert.js: do not edit. The Gmail reader the page hands to an owner (Found work settings).\n// The workspace's public address and key come from config.js, so they are never typed in twice.\nimport { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY } from './config.js';\n\nexport const READER_TEMPLATE = ${JSON.stringify(tpl)};\nexport const readerScript = (token) => READER_TEMPLATE.replace('__TOKEN__', () => String(token)).replace('__URL__', () => SUPABASE_URL).replace('__KEY__', () => SUPABASE_PUBLISHABLE_KEY);\n`;
}

const GS = 'tools/gmail-gets-reader/Code.gs', MOD = 'architecture/js/gmail-reader-script.js';
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, GS), buildScript());
  writeFileSync(path.join(root, MOD), buildModule());
  console.log(`${GS} and ${MOD} written`);
}
