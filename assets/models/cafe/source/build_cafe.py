def render_all():
    sc = bpy.context.scene
    sc.render.engine = 'CYCLES'
    sc.cycles.device = 'CPU'
    sc.cycles.samples = SAMPLES
    sc.cycles.use_denoising = True
    try:
        sc.cycles.denoiser = 'OPENIMAGEDENOISE'
    except Exception:
        pass
    sc.cycles.max_bounces = 6
    sc.render.resolution_x, sc.render.resolution_y = RES
    sc.render.film_transparent = False
    sc.view_settings.view_transform = 'AgX'
    w = bpy.data.worlds.new('world')
    w.use_nodes = True
    bg = w.node_tree.nodes['Background']
    bg.inputs['Color'].default_value = (*srgb('#F4EFE8'), 1)
    bg.inputs['Strength'].default_value = 0.9
    sc.world = w
    sun_d = bpy.data.lights.new('sun', 'SUN')
    sun_d.energy = 3.2
    sun_d.angle = math.radians(6)
    sun_d.color = (1.0, 0.96, 0.9)
    sun = bpy.data.objects.new('sun', sun_d)
    RENDER_ONLY.objects.link(sun)
    sun.rotation_euler = (math.radians(38), math.radians(-18), math.radians(28))
    cam_d = bpy.data.cameras.new('cam')
    cam = bpy.data.objects.new('cam', cam_d)
    RENDER_ONLY.objects.link(cam)
    sc.camera = cam
    demo_state()
    shots = [('cafe-hero', (16.0, 19.0, 24.0), (0.0, 0.0, 0.5), 34),
             ('cafe-counter-detail', (8.6, 2.9, 5.2), (4.4, 1.2, 0.9), 38),
             ('cafe-pass-detail', (-0.6, 2.4, 0.6), (2.0, 1.3, -2.7), 42)]
    only = [x for x in os.environ.get('CAFE_SHOTS', '').split(',') if x]   # e.g. CAFE_SHOTS=cafe-pass-detail renders one still
    out = []
    for name, eye, tgt, fov in shots:
        if only and name not in only:
            continue
        look_at(cam, eye, tgt)
        cam_d.angle = math.radians(fov)
        sc.render.filepath = os.path.join(OUT, 'renders', name + '.png')
        bpy.ops.render.render(write_still=True)
        out.append(sc.render.filepath)
        print('RENDERED', sc.render.filepath)
    return out


