def empty(name, parent=None, at=(0, 0, 0), **props):
    o = bpy.data.objects.new(name, None)
    o.empty_display_size = 0.2
    o.location = at
    link(o)
    if parent:
        o.parent = parent
    for k, v in props.items():
        o[k] = v
    return o


def mesh_obj(name, bm, material, parent=None, loc=(0, 0, 0), coll=None, **props):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    me.materials.append(material)
    for poly in me.polygons:
        poly.use_smooth = False
    o = bpy.data.objects.new(name, me)
    o.location = loc
    link(o, coll)
    if parent:
        o.parent = parent
    for k, v in props.items():
        o[k] = v
    return o


def _bevel(bm, w, seg=1):
    if w > 0:
        bmesh.ops.bevel(bm, geom=list(bm.edges), offset=w, segments=seg, affect='EDGES', profile=0.5, clamp_overlap=True)


def bm_box(w, h, d, bevel=0.0, seg=1):
    """Box in plan terms: w along X, h up, d along street axis. Centred on origin (Blender coords)."""
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    bmesh.ops.scale(bm, vec=(w, d, h), verts=bm.verts)
    _bevel(bm, min(bevel, w / 2.2, h / 2.2, d / 2.2), seg)
    return bm


def bm_cyl(r1, r2, h, seg=16, caps=True, axis='Y'):
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=caps, cap_tris=False, segments=seg, radius1=r2, radius2=r1, depth=h)
    if axis == 'X':
        bmesh.ops.rotate(bm, cent=(0, 0, 0), matrix=Matrix.Rotation(math.pi / 2, 3, 'Y'), verts=bm.verts)
    elif axis == 'Z':  # along the plan street axis = Blender -Y
        bmesh.ops.rotate(bm, cent=(0, 0, 0), matrix=Matrix.Rotation(math.pi / 2, 3, 'X'), verts=bm.verts)
    return bm


def bm_sphere(r, seg=12, rings=8):
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=seg, v_segments=rings, radius=r)
    return bm


def box(name, w, h, d, X, Y, Z, m, bevel=0.012, parent=None, seg=1, **props):
    return mesh_obj(name, bm_box(w, h, d, bevel, seg), M[m] if isinstance(m, str) else m, parent, P(X, Y, Z), **props)


def cyl(name, r1, r2, h, X, Y, Z, m, seg=16, parent=None, axis='Y', caps=True, **props):
    return mesh_obj(name, bm_cyl(r1, r2, h, seg, caps, axis), M[m] if isinstance(m, str) else m, parent, P(X, Y, Z), **props)


def sphere(name, r, X, Y, Z, m, seg=12, rings=8, parent=None, scale=(1, 1, 1), **props):
    o = mesh_obj(name, bm_sphere(r, seg, rings), M[m] if isinstance(m, str) else m, parent, P(X, Y, Z), **props)
    o.scale = (scale[0], scale[2], scale[1])
    return o


def tube(name, pts, r, m, parent=None, seg=8):
    """A bent tube through plan points (steam wands, rails, cords)."""
    cu = bpy.data.curves.new(name, 'CURVE')
    cu.dimensions = '3D'
    sp = cu.splines.new('POLY')
    sp.points.add(len(pts) - 1)
    for i, p in enumerate(pts):
        v = P(*p)
        sp.points[i].co = (v.x, v.y, v.z, 1)
    cu.bevel_depth = r
    cu.bevel_resolution = max(1, seg // 4 - 1)
    cu.use_fill_caps = True
    o = bpy.data.objects.new(name + '_curve', cu)
    link(o)
    me = bpy.data.meshes.new_from_object(o.evaluated_get(bpy.context.evaluated_depsgraph_get()))
    bpy.data.objects.remove(o)
    me.materials.clear()
    me.materials.append(M[m])
    ob = bpy.data.objects.new(name, me)
    link(ob)
    if parent:
        ob.parent = parent
    return ob


def join(name, objs, parent=None, pivot=None, **props):
    """Join objects (keeps per-face materials). Optional pivot is a plan point; the object origin moves there."""
    objs = [o for o in objs if o]
    bpy.context.view_layer.update()
    bm = bmesh.new()
    mats = []
    for o in objs:
        me = o.data
        tmp = bmesh.new()
        tmp.from_mesh(me)
        bmesh.ops.transform(tmp, matrix=o.matrix_world if o.parent is None else o.matrix_world, verts=tmp.verts)
        offset = len(mats)
        for mm in me.materials:
            mats.append(mm)
        for f in tmp.faces:
            f.material_index += offset
        tmpme = bpy.data.meshes.new('_tmp')
        tmp.to_mesh(tmpme)
        tmp.free()
        bm.from_mesh(tmpme)
        bpy.data.meshes.remove(tmpme)
    # de-duplicate materials
    uniq = []
    remap = {}
    for i, mm in enumerate(mats):
        if mm not in uniq:
            uniq.append(mm)
        remap[i] = uniq.index(mm)
    for f in bm.faces:
        f.material_index = remap.get(f.material_index, 0)
    for o in objs:
        me = o.data
        bpy.data.objects.remove(o)
        if me.users == 0:
            bpy.data.meshes.remove(me)
    me = bpy.data.meshes.new(name)
    piv = P(*pivot) if pivot is not None else Vector((0, 0, 0))
    bmesh.ops.translate(bm, vec=-piv, verts=bm.verts)
    bm.to_mesh(me)
    bm.free()
    for mm in uniq:
        me.materials.append(mm)
    ob = bpy.data.objects.new(name, me)
    ob.location = piv
    link(ob)
    if parent:
        ob.parent = parent
    for k, v in props.items():
        ob[k] = v
    return ob


def instance(name, data, X, Y, Z, rot_y=0.0, parent=None, scale=1.0, **props):
    """Linked duplicate: shares mesh data (the glTF exporter writes one mesh, many nodes)."""
    o = bpy.data.objects.new(name, data)
    o.location = P(X, Y, Z)
    o.rotation_euler = (0, 0, rot_y)  # plan rotation about up axis
    o.scale = (scale, scale, scale)
    link(o)
    if parent:
        o.parent = parent
    for k, v in props.items():
        o[k] = v
    return o


def text(name, body, X, Y, Z, size, m='navy', face='z', parent=None, coll=None, align='CENTER', extrude=0.002):
    """Navy label text, converted to mesh. face='z' faces the street (+Z plan); 'x' faces +X; '-z' faces the kitchen."""
    cu = bpy.data.curves.new(name, 'FONT')
    cu.body = body
    cu.size = size
    cu.align_x = align
    cu.align_y = 'CENTER'
    cu.extrude = extrude
    cu.resolution_u = 2
    o = bpy.data.objects.new(name + '_font', cu)
    link(o, coll)
    o.rotation_euler = (math.pi / 2, 0, {'z': 0, 'x': math.pi / 2, '-z': math.pi, '-x': -math.pi / 2}[face])
    o.location = P(X, Y, Z)
    bpy.context.view_layer.update()
    me = bpy.data.meshes.new_from_object(o.evaluated_get(bpy.context.evaluated_depsgraph_get()))
    me.transform(o.matrix_world)
    (coll or COLL).objects.unlink(o)
    bpy.data.objects.remove(o)
    me.materials.clear()
    me.materials.append(M[m])
    ob = bpy.data.objects.new(name, me)
    link(ob, coll)
    if parent:
        ob.parent = parent
    return ob


def uv_quad_face(name, w, h, X, Y, Z, face, m='board', parent=None, **props):
    """Upright rectangle with a 0..1 UV map, for boards whose content is drawn live by the page."""
    bm = bmesh.new()
    uv = bm.loops.layers.uv.new('UVMap')
    hw, hh = w / 2, h / 2
    if face == 'x':      # faces +X plan
        vs = [(0, -hw, -hh), (0, hw, -hh), (0, hw, hh), (0, -hw, hh)]
    else:                # faces +Z plan (towards the street)
        vs = [(-hw, 0, -hh), (hw, 0, -hh), (hw, 0, hh), (-hw, 0, hh)]
    verts = [bm.verts.new(v) for v in vs]
    f = bm.faces.new(verts)
    for loop, t in zip(f.loops, [(0, 0), (1, 0), (1, 1), (0, 1)]):
        loop[uv].uv = t
    return mesh_obj(name, bm, M[m], parent, P(X, Y, Z), **props)


