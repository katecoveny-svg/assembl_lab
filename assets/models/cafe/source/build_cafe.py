def tri_count(objs):
    dg = bpy.context.evaluated_depsgraph_get()
    n = 0
    for o in objs:
        if o.type != 'MESH':
            continue
        me = o.evaluated_get(dg).data
        me.calc_loop_triangles()
        n += len(me.loop_triangles)
    return n


